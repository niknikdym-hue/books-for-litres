from pathlib import Path

ROOT = Path('ne-ver-golosu/manuscript')


def replace_between(text: str, start: str, end: str, new_block: str) -> str:
    i = text.find(start)
    if i < 0:
        print('WARN missing start:', start)
        return text
    j = text.find(end, i + len(start))
    if j < 0:
        print('WARN missing end:', end)
        return text
    return text[:i] + new_block.rstrip() + '\n\n' + text[j:]


def replace(path_name, old, new):
    path = ROOT / path_name
    text = path.read_text(encoding='utf-8')
    if old not in text:
        print(f'WARN not found {path_name}: {old[:100]}')
        return
    path.write_text(text.replace(old, new), encoding='utf-8')
    print('changed', path_name)

